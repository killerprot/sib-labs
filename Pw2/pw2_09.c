#include <stdio.h>

int main(void)
{
    /*
       Ожидаемый результат до запуска: на экране должно остаться слово STOP.

       Объяснение движения курсора:
       1) printf("START") - на экране START, курсор стоит после буквы T.
       2) Три раза \b - курсор сдвигается влево на 3 позиции и встаёт
          на букву A (S T [A] R T). \b только двигает курсор и ничего не стирает.
       3) printf("OP ") - буквы O и P записываются поверх A и R, а пробел
          затирает последнюю букву T. На экране получается "STOP ".
       4) Ещё один \b - курсор возвращается на пробел (чтобы он не торчал
          за словом).
       5) В конце \n (перенос строки) и \a (звуковой сигнал).
    */

    printf("START");
    printf("\b\b\b");
    printf("OP ");
    printf("\b");
    printf("\n\a");

    return 0;
}
