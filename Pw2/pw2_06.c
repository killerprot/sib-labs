#include <stdio.h>
#include <stdint.h>

int main(void)
{
    int number;
    uint8_t x;      
    uint8_t add;
    uint8_t mul2;
    uint8_t sqr;

    scanf("%d", &number);
    x = number;     

    
    add = x + 10;   
    mul2 = x * 2;   
    sqr = x * x;   

    printf("ADD: %u\n", (unsigned int)add);
    printf("MUL2: %u\n", (unsigned int)mul2);
    printf("SQR: %u\n", (unsigned int)sqr);

    /*
       Почему результаты "сворачиваются" по модулю 256?
       Тип uint8_t занимает 8 бит и может хранить числа только от 0 до 255.
       Когда результат вычисления больше 255, в переменную попадают только
       младшие 8 бит, а старшие отбрасываются. Это то же самое, что взять
       остаток от деления на 256.
       Пример для 250: 250 + 10 = 260, 260 % 256 = 4;
       250 * 2 = 500, 500 % 256 = 244; 250 * 250 = 62500, 62500 % 256 = 36.
       Это похоже на счётчик пробега автомобиля, который после максимума
       снова начинает с нуля.
    */

    return 0;
}
