#include <stdio.h>

int main(void)
{
   
    int dec = 10;
    int oct = 010;
    int hex = 0x10;

    char c = 'A';

    printf("DEC_10: %d\n", dec);
    printf("OCT_10: %d\n", oct);
    printf("HEX_10: %d\n", hex);

   
    printf("INT_SUFFIX: %zu %zu %zu %zu\n",
           sizeof(10), sizeof(10u), sizeof(10LL), sizeof(10ULL));

    
    printf("FLOAT_SUFFIX: %zu %zu %zu\n",
           sizeof(0.1f), sizeof(0.1), sizeof(0.1L));

   
    printf("FLOAT_EQ: %d\n", 0.1f == 0.1);

    
    printf("CHAR_FORMS: %d %d %d\n", 'A', '\x41', '\101');

    
    printf("CHAR_LIT_VAR_STR: %zu %zu %zu\n",
           sizeof('A'), sizeof(c), sizeof("A"));

    /*
       Объяснения:

       1) Системы счисления литералов:
          10   - десятичная (обычное число), значение 10
          010  - восьмеричная (начинается с 0), значение 8
          0x10 - шестнадцатеричная (начинается с 0x), значение 16

       2) Суффиксы задают тип литерала:
          u  - unsigned (без знака), LL - long long, ULL - unsigned long long,
          f  - float, L у вещественного - long double.
          Без суффикса целое - int, вещественное - double.

       3) 0.1f не равно 0.1, потому что число 0.1 нельзя точно записать
          в двоичном виде. float хранит его с меньшим числом разрядов
          (примерно 7 цифр), а double - с большим (примерно 15-16 цифр).
          Поэтому в памяти получаются два разных приближения числа 0.1.
          При сравнении float приводится к double, но потерянные
          разряды не возвращаются, и значения не совпадают.

       4) В языке Си символьный литерал 'A' имеет тип int, поэтому его
          размер 4 байта (на типичной системе). А переменная типа char
          по определению занимает 1 байт. Строка "A" - это массив из двух
          символов: 'A' и завершающий '\0', поэтому её размер 2 байта.
    */

    return 0;
}
