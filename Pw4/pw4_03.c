#include <stdio.h>

int main(void)
{
    int n;
    int count = 1;
    int value = 1;

    /* Вариант 18: последовательность сумм натуральных чисел. */
    scanf("%d", &n);
    while (count <= n) {
        printf("%d", value);
        if (count < n) {
            printf(" ");
        }
        count++;
        value += count;
    }
    printf("\n");

    return 0;
}

